class SaveTests(unittest.TestCase):
    def test_crc_known_vector(self):
        self.assertEqual(le3.reader.crc32_bzip2(b"123456789"), 0xFC891918)

    def test_full_structure_and_acceptance_boundary(self):
        raw, offsets = fixture()
        save = le3.Save(raw)
        self.assertEqual(save.pos, len(raw) - 4)
        self.assertEqual(save.data["base_level_name"], "BioP_Test")
        self.assertEqual(save.data["player"]["level"], 10)
        self.assertEqual(save.data["location"], dict(x=1, y=2, z=3))
        info = save.info()
        self.assertTrue(info["full_decode"])
        self.assertFalse(info["fixture_ready"])
        self.assertFalse(info["native_verified"])
        self.assertEqual(info["opaque_bytes"], 0)
        self.assertEqual(save.value("plot.integers.0"), {"key": 42, "value": -1})
        self.assertEqual(save.value("player.powers.0.evolved_choice_5"), 5)
        self.assertEqual(save.value("galaxy_map.systems.0.reaper_alert_level"), 0.75)
        self.assertEqual(save.value("saved_objective_text"), 77)

    def test_wrong_game_endian_and_checksum(self):
        raw, _ = fixture()
        for prefix in (i(30), struct.pack(">i", 59), i(60)):
            with self.subTest(prefix=prefix), self.assertRaisesRegex(le3.SaveError, "version 59"):
                le3.Save(checksum(prefix + raw[4:-4]))
        with self.assertRaisesRegex(le3.SaveError, "CRC"):
            le3.Save(raw[:-1] + bytes([raw[-1] ^ 1]))

    def test_bounded_negative_fields_even_with_valid_crc(self):
        raw, offsets = fixture()
        cases = [("seconds", f(float("nan"))), ("difficulty", b"\x05"),
                 ("levels", i(-1)), ("placeables", i(1000001)),
                 ("player_bool", i(2)), ("origin", b"\x04"), ("class", i(-2147483648)), ("conversation", b"\x03")]
        for key, replacement in cases:
            at = offsets[key]
            bad = raw[:at] + replacement + raw[at + len(replacement):-4]
            with self.subTest(key=key), self.assertRaises(le3.SaveError):
                le3.Save(checksum(bad))

    def test_truncated_prefix_or_absent_tail(self):
        raw, offsets = fixture()
        for stop in (5, offsets["class"] + 6, offsets["tail"]):
            with self.subTest(stop=stop), self.assertRaises(le3.SaveError):
                le3.Save(checksum(raw[:stop]))

    def test_unterminated_and_invalid_wide_string(self):
        raw, offsets = fixture()
        at = offsets["class"]
        length = struct.unpack_from("<i", raw, at)[0]
        end = at + 4 + length - 1
        with self.assertRaisesRegex(le3.SaveError, "Unterminated"):
            le3.Save(checksum(raw[:end] + b"x" + raw[end + 1:-4]))
        # Wide debug name: isolated high surrogate, followed by its terminator.
        old_length = -struct.unpack_from("<i", raw, 4)[0] * 2
        bad = raw[:4] + i(-2) + b"\x00\xd8\x00\x00" + raw[8 + old_length:-4]
        with self.assertRaisesRegex(le3.SaveError, "Invalid string"):
            le3.Save(checksum(bad))

    def test_roundtrip_rebuilds_every_field_without_source_bytes(self):
        raw, _ = fixture()
        save = le3.Save(raw)
        output, receipt = save.roundtrip()
        self.assertEqual(output, raw)
        self.assertEqual(receipt["input_sha256"], receipt["output_sha256"])
        self.assertEqual(receipt["operation"], "roundtrip")
        self.assertTrue(receipt["serialization_roundtrip"])
        self.assertFalse(receipt["fixture_ready"])
        payload = save.encode(le3.SCHEMA, save.data)
        save.raw = b"unavailable original bytes"
        self.assertEqual(checksum(payload), raw)
        with self.assertRaisesRegex(le3.SaveError, "recipe requires"):
            save.prepare({"set": {"player.level": 99}})

    def test_unknown_tail_and_duplicate_keyed_records_rejected(self):
        raw, offsets = fixture()
        with self.assertRaisesRegex(le3.SaveError, "trailing"):
            le3.Save(checksum(raw[:-4] + b"unknown"))
        for group in ("war_assets", "plot_integers"):
            at = offsets[group] + 4
            changed = raw[:at + 8] + raw[at:at + 4] + raw[at + 12:-4]
            with self.subTest(group=group), self.assertRaisesRegex(le3.SaveError, "Duplicate map"):
                le3.Save(checksum(changed))
        with self.assertRaises(le3.SaveError):
            le3.Save(checksum(raw[:offsets["tail"]] + b"opaque-not-a-real-inventory"))

    def recipe(self, save, values):
        return dict(schema_version=1, id="synthetic-resource-only", game="LE3", save_version=59,
                    expected_input_sha256=le3.reader.sha256(save.raw),
                    expect={p: save.value(p) for p in values}, set=values)

    def test_resource_edits_change_only_declared_bytes_and_checksum(self):
        raw, _ = fixture()
        save = le3.Save(raw)
        values = {"player.credits": 0, "player.medigel": 1, "player.grenades": 4,
                  "player.current_fuel": 10.25, "player.health": 100.5,
                  "player.weapons.0.ammo_total": 55, "squad.0.grenades": 0,
                  "squad.0.weapons.0.ammo_used_count": 1}
        recipe = self.recipe(save, values)
        recipe["expect"].update({"player.weapons.0.class_name": "SFXWeapon_Test", "squad.0.tag": "hench_test",
                                "squad.0.weapons.0.class_name": "SFXWeapon_Test"})
        after, changes = save.prepare(recipe)
        actual = {r["path"] for r in le3.reader.diff(save, after)}
        self.assertEqual(actual, set(values))
        allowed = set(range(len(raw) - 4, len(raw)))
        for change in changes:
            allowed.update(range(change["offset"], change["offset"] + change["size"]))
            self.assertEqual(after.value(change["path"]), values[change["path"]])
        self.assertTrue(all(a == b or n in allowed for n, (a, b) in enumerate(zip(raw, after.raw))))
        self.assertEqual(after.roundtrip()[0], after.raw)
        self.assertFalse(le3.make_receipt("prepare", save, after, changes, recipe=recipe, recipe_raw=b"{}")["fixture_ready"])

    def test_typed_resource_and_story_refusals(self):
        save = le3.Save(fixture()[0])
        for path, value in (("player.credits", True), ("player.credits", -1), ("player.credits", 2**31),
                            ("player.medigel", 1.5), ("player.current_fuel", float("inf")),
                            ("player.current_fuel", 1e40), ("player.level", 60),
                            ("plot.integers.0.value", 5), ("galaxy_map.systems.0.reaper_alert_level", 0),
                            ("player.weapons.0.ammo_total", 5), ("squad.0.grenades", 5)):
            with self.subTest(path=path, value=value), self.assertRaises(le3.SaveError):
                save.prepare(self.recipe(save, {path: value}))
        recipe = self.recipe(save, {"player.credits": 5})
        for key, value in (("game", "LE2"), ("save_version", 30), ("expected_input_sha256", "0" * 64),
                           ("expect", {"player.credits": 8})):
            with self.subTest(key=key), self.assertRaises(le3.SaveError):
                save.prepare(dict(recipe, **{key: value}))

    def test_outputs_never_overwrite_source_or_alias_receipt(self):
        raw, _ = fixture()
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / "source.pcsav"
            source.write_bytes(raw)
            after, receipt = le3.Save.load(source).roundtrip()
            with self.assertRaises(le3.SaveError):
                le3.reader.write_outputs(source, after, Path(tmp) / "receipt.json", receipt)
            target = Path(tmp) / "new.pcsav"
            with self.assertRaises(le3.SaveError):
                le3.reader.write_outputs(target, after, target, receipt)
            self.assertEqual(source.read_bytes(), raw)
            self.assertFalse(target.exists())
            le3.reader.write_outputs(target, after, Path(tmp) / "receipt.json", receipt)
            self.assertEqual(target.read_bytes(), raw)

    def test_inventory_reports_each_refusal_without_writing(self):
        raw, _ = fixture()
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "ok.pcsav").write_bytes(raw)
            (root / "wrong.pcsav").write_bytes(checksum(i(30) + raw[4:-4]))
            before = {p.name: p.read_bytes() for p in root.iterdir()}
            result = le3.inventory(root)
            self.assertEqual((result["inspected"], result["failed"]), (2, 1))
            self.assertEqual(before, {p.name: p.read_bytes() for p in root.iterdir()})

    @unittest.skipUnless(os.environ.get("LE3_TEST_SAVE_ROOT"), "private corpus is opt-in")
    def test_private_corpus_read_only(self):
        root = Path(os.environ["LE3_TEST_SAVE_ROOT"])
        files = list(root.rglob("*.pcsav"))
        self.assertTrue(files)
        for path in files:
            with self.subTest(file=path.name):
                raw = path.read_bytes()
                save = le3.Save(raw)
                self.assertEqual(save.roundtrip()[0], raw)
                self.assertEqual(path.read_bytes(), raw)

    @unittest.skipUnless(os.environ.get("LE3_TEST_SAVE_ROOT") and os.environ.get("LE3_TSE_ORACLE"), "independent private oracle is opt-in")
    def test_private_corpus_full_independent_comparison_before_resource_clones(self):
        checker_path = TOOL.parent / "qa-le2/check-save-oracle.py"
        checker_spec = importlib.util.spec_from_file_location("le3_oracle_tests", checker_path)
        checker = importlib.util.module_from_spec(checker_spec)
        checker_spec.loader.exec_module(checker)
        files = list(Path(os.environ["LE3_TEST_SAVE_ROOT"]).rglob("*.pcsav"))
        self.assertTrue(files)
        with tempfile.TemporaryDirectory() as tmp:
            for index, path in enumerate(files):
                before = path.read_bytes()
                result = checker.verify(path, Path(os.environ["LE3_TSE_ORACLE"]), Path(tmp) / str(index), TOOL)
                self.assertTrue(result["passed"])
                self.assertEqual(result["native_load"], "untested")
                self.assertEqual(path.read_bytes(), before)


