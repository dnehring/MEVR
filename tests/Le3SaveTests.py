spec.loader.exec_module(le3)


def i(value=0):
    return struct.pack("<i", value)


def f(value=0):
    return struct.pack("<f", value)


def string(value="", wide=False):
    if not value:
        return i()
    raw = value.encode("utf-16-le" if wide else "cp1252") + (b"\0\0" if wide else b"\0")
    return i(-len(raw) // 2 if wide else len(raw)) + raw


def checksum(payload):
    return payload + struct.pack("<I", le3.reader.crc32_bzip2(payload))


